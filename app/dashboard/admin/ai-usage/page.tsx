'use client';

import { useState, useEffect } from 'react';
import { Icon } from '@/components/icons';

interface ProviderStats {
  provider: string;
  cost: number;
  inputTokens: number;
  outputTokens: number;
}

interface OperationCost {
  name: string;
  value: number;
}

interface DailyCost {
  date: string;
  cost: number;
}

interface UserCost {
  name: string;
  cost: number;
}

interface AgentStat {
  name: string;
  count: number;
  cost: number;
}

export default function AdminAIUsage() {
  const [loading, setLoading] = useState(true);
  const [providers, setProviders] = useState<ProviderStats[]>([]);
  const [operations, setOperations] = useState<OperationCost[]>([]);
  const [dailyCosts, setDailyCosts] = useState<DailyCost[]>([]);
  const [users, setUsers] = useState<UserCost[]>([]);
  const [agents, setAgents] = useState<AgentStat[]>([]);

  useEffect(() => {
    async function loadAIUsage() {
      try {
        const res = await fetch('/api/admin/ai-usage');
        if (res.ok) {
          const data = await res.json();
          setProviders(data.providersBreakdown);
          setOperations(data.operationsBreakdown);
          setDailyCosts(data.dailyCosts);
          setUsers(data.usersBreakdown);
          setAgents(data.agentsBreakdown);
        }
      } catch (err) {
        console.error('Failed to load AI usage metrics:', err);
      } finally {
        setLoading(false);
      }
    }
    loadAIUsage();
  }, []);

  if (loading) {
    return (
      <div className="p-6 border border-border-subtle bg-bg-surface/50 rounded-xl space-y-6 animate-pulse">
        <div className="h-6 w-1/4 bg-border-subtle rounded" />
        <div className="grid grid-cols-2 gap-4">
          <div className="h-[200px] bg-border-subtle rounded" />
          <div className="h-[200px] bg-border-subtle rounded" />
        </div>
      </div>
    );
  }

  const maxDaily = Math.max(...dailyCosts.map(d => d.cost), 1);
  const totalAIPlatformCost = providers.reduce((acc, curr) => acc + curr.cost, 0);

  return (
    <div className="space-y-6 animate-[fadeIn_0.25s_ease-out]">
      {/* Dynamic Summary Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        {/* Token count */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Grid size={13} className="text-accent" />
              Total Ingest Tokens
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Platform token inputs across all providers</p>
          </div>
          <div className="text-2xl font-bold font-mono tracking-tight text-text-primary">
            {providers.reduce((acc, curr) => acc + curr.inputTokens, 0).toLocaleString()}
          </div>
        </div>

        {/* Output Token count */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Code size={13} className="text-blue-400" />
              Total Output Tokens
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Response tokens generated by model nodes</p>
          </div>
          <div className="text-2xl font-bold font-mono tracking-tight text-text-primary">
            {providers.reduce((acc, curr) => acc + curr.outputTokens, 0).toLocaleString()}
          </div>
        </div>

        {/* Aggregated AI cost */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Sparkle size={13} className="text-purple-400" />
              Total AI Budget
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Total platform budget utilized</p>
          </div>
          <div className="flex justify-between items-baseline">
            <div className="text-2xl font-bold font-mono tracking-tight text-accent">
              ${totalAIPlatformCost.toFixed(4)}
            </div>
            {operations.length > 0 && (
              <div className="text-[9px] font-mono text-text-muted">
                {Math.round(((operations[1]?.value || 0) / (totalAIPlatformCost || 1)) * 100)}% analysis
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Detail breakdowns & Charts */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Daily cost sparkline graph */}
        <div className="lg:col-span-2 p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div className="flex justify-between items-center">
            <div>
              <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
                <Icon.Grid size={13} className="text-accent" />
                Time Series Compute Costs
              </h3>
              <p className="text-[10px] text-text-muted mt-0.5">30-day overview of AI budget changes</p>
            </div>
            <div className="text-[10px] font-mono text-accent font-bold">${totalAIPlatformCost.toFixed(4)} total</div>
          </div>

          {/* SVG Line Chart */}
          <div className="w-full h-[200px]">
            {dailyCosts.length === 0 ? (
              <div className="w-full h-full flex items-center justify-center text-xs text-text-muted font-mono border border-dashed border-border-subtle rounded-lg">
                No billing history logs.
              </div>
            ) : (
              <svg className="w-full h-full" viewBox="0 0 600 200" preserveAspectRatio="none">
                <defs>
                  <linearGradient id="costGlow" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="0%" stopColor="#146ef5" stopOpacity="0.22" />
                    <stop offset="100%" stopColor="#146ef5" stopOpacity="0.0" />
                  </linearGradient>
                </defs>

                {/* Gridlines */}
                {[0, 25, 50, 75, 100].map(p => (
                  <line
                    key={p}
                    x1="0"
                    y1={20 + (p * 1.5)}
                    x2="600"
                    y2={20 + (p * 1.5)}
                    stroke="var(--border-subtle)"
                    strokeWidth="0.5"
                    strokeDasharray="4 6"
                    opacity="0.4"
                  />
                ))}

                {/* Glow area */}
                <path
                  d={`
                    M 0 180
                    ${dailyCosts.map((d, i) => {
                      const x = (i / (dailyCosts.length - 1)) * 600;
                      const y = 180 - (d.cost / maxDaily) * 150;
                      return `L ${x} ${y}`;
                    }).join(' ')}
                    L 600 180 Z
                  `}
                  fill="url(#costGlow)"
                />

                {/* Main line */}
                <path
                  d={dailyCosts.map((d, i) => {
                    const x = (i / (dailyCosts.length - 1)) * 600;
                    const y = 180 - (d.cost / maxDaily) * 150;
                    return `${i === 0 ? 'M' : 'L'} ${x} ${y}`;
                  }).join(' ')}
                  fill="none"
                  stroke="#146ef5"
                  strokeWidth="2"
                  strokeLinecap="round"
                />
              </svg>
            )}
          </div>

          <div className="flex justify-between text-[9px] font-mono text-text-muted px-1">
            <span>{dailyCosts[0]?.date || 'Oct 23'}</span>
            <span>{dailyCosts[Math.round(dailyCosts.length / 2)]?.date || 'Nov 07'}</span>
            <span>{dailyCosts[dailyCosts.length - 1]?.date || 'Nov 22'}</span>
          </div>
        </div>

        {/* Top User Consumers list */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Shield size={13} className="text-blue-400" />
              Highest Consumer Budgets
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Top 5 analysts by resource consumption</p>
          </div>

          <div className="space-y-3">
            {users.length === 0 ? (
              <div className="text-center py-8 font-mono text-[10px] text-text-muted italic border border-dashed border-border-subtle rounded-lg">
                No user billing data computed.
              </div>
            ) : (
              users.map((u, i) => {
                const maxUserCost = Math.max(...users.map(us => us.cost), 1);
                const barPct = Math.round((u.cost / maxUserCost) * 100);

                return (
                  <div key={i} className="space-y-1 p-2 rounded bg-bg-surface border border-border-subtle/50">
                    <div className="flex justify-between text-[10px] font-mono">
                      <span className="text-text-primary font-bold">{u.name}</span>
                      <span className="text-accent font-semibold">${u.cost.toFixed(4)}</span>
                    </div>
                    <div className="h-1 bg-border-subtle/30 rounded-full overflow-hidden">
                      <div className="h-full bg-accent rounded-full" style={{ width: `${barPct}%` }} />
                    </div>
                  </div>
                );
              })
            )}
          </div>
        </div>
      </div>

      {/* Provider Details ledger & Agents cost statistics */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Provider ledger */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Sparkle size={13} className="text-purple-400" />
              Ingestion Nodes Ledger
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Token counts and pricing metrics by provider network</p>
          </div>

          <div className="border border-border-subtle/50 rounded-lg overflow-hidden bg-black/10">
            <table className="w-full text-left border-collapse text-xs font-mono">
              <thead>
                <tr className="bg-bg-surface border-b border-border-subtle/50 text-[9px] uppercase tracking-wider text-text-muted">
                  <th className="p-3">Model Provider</th>
                  <th className="p-3">Input Tokens</th>
                  <th className="p-3">Output Tokens</th>
                  <th className="p-3 text-right">Aggregate Cost</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border-subtle/30">
                {providers.map(p => (
                  <tr key={p.provider} className="hover:bg-bg-surface-2/30">
                    <td className="p-3 text-text-primary font-bold">{p.provider}</td>
                    <td className="p-3 text-text-muted">{p.inputTokens.toLocaleString()}</td>
                    <td className="p-3 text-text-muted">{p.outputTokens.toLocaleString()}</td>
                    <td className="p-3 text-right text-accent font-semibold">${p.cost.toFixed(4)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>

        {/* Cognitive Agent Overhead ledger */}
        <div className="p-5 rounded-xl border border-border-subtle bg-bg-surface/85 backdrop-blur-md space-y-4">
          <div>
            <h3 className="text-xs font-semibold text-text-primary tracking-wide flex items-center gap-1.5">
              <Icon.Branch size={13} className="text-accent" />
              Cognitive Agent Overhead
            </h3>
            <p className="text-[10px] text-text-muted mt-0.5">Run metrics and compute budget split across automated agents</p>
          </div>

          <div className="border border-border-subtle/50 rounded-lg overflow-hidden bg-black/10">
            <table className="w-full text-left border-collapse text-xs font-mono">
              <thead>
                <tr className="bg-bg-surface border-b border-border-subtle/50 text-[9px] uppercase tracking-wider text-text-muted">
                  <th className="p-3">Specialized Agent</th>
                  <th className="p-3">Total Executions</th>
                  <th className="p-3 text-right">Accumulated Cost</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border-subtle/30">
                {agents.length === 0 ? (
                  <tr>
                    <td colSpan={3} className="p-6 text-center text-text-muted italic">
                      No agent executions recorded yet.
                    </td>
                  </tr>
                ) : (
                  agents.map(a => (
                    <tr key={a.name} className="hover:bg-bg-surface-2/30">
                      <td className="p-3 text-text-primary font-bold">{a.name}</td>
                      <td className="p-3 font-semibold text-text-muted">{a.count} runs</td>
                      <td className="p-3 text-right text-accent font-semibold">${a.cost.toFixed(4)}</td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>
    </div>
  );
}
